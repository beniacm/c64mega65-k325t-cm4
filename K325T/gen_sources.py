#!/usr/bin/env python3
"""Write sources.tcl: the R6 project's synthesis sources (CORE/CORE-R6.xpr) with their
file types, minus the R6 board top, plus the K325T files and the two files shared with
the MEGA65 core port (sd_emu, rk_bridge from ../mega65-core)."""
import os, re
here = os.path.dirname(os.path.abspath(__file__))
root = os.path.dirname(here)
x = open(os.path.join(root, 'CORE/CORE-R6.xpr')).read()
a = x.index('<FileSet Name="sources_1"'); b = x.index('</FileSet>', a)
out = ['# GENERATED by K325T/gen_sources.py -- do not edit']
for p, body in re.findall(r'<File Path="([^"]+)">(.*?)</File>', x[a:b], re.S):
    if p.endswith('top_mega65-r6.vhd') or 'synthesis' not in body:
        continue
    path = os.path.normpath(p.replace('$PPRDIR', os.path.join(root, 'CORE')))
    assert os.path.exists(path), path
    m = re.search(r'SFType="([^"]+)"', body)
    ext = path.rsplit('.', 1)[-1]
    ft = {'VHDL2008': 'VHDL 2008', 'SVerilog': 'SystemVerilog'}.get(m.group(1) if m else '',
         {'vhd': 'VHDL', 'vhdl': 'VHDL', 'v': 'Verilog', 'sv': 'SystemVerilog'}[ext])
    out.append('add_files -norecurse {%s}; set_property FILE_TYPE {%s} [get_files {%s}]' % (path, ft, path))
mc = os.path.normpath(os.path.join(root, '../mega65-core/src/vhdl'))
for f in [os.path.join(here, 'top_qmtech_k325t_cm4.vhd'), os.path.join(here, 'avm_mig.vhd'),
          os.path.join(here, 'm65kbd_emu.vhd'), os.path.join(mc, 'sd_emu.vhdl'),
          os.path.join(mc, 'rk_bridge.vhdl')]:
    assert os.path.exists(f), f
    out.append('add_files -norecurse {%s}; set_property FILE_TYPE {VHDL 2008} [get_files {%s}]' % (f, f))
open(os.path.join(here, 'sources.tcl'), 'w').write('\n'.join(out) + '\n')
print('sources.tcl: %d files' % (len(out) - 1))
